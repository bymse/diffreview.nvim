local h = require('integration.ui.comments.helpers')
local git_repo = require('helpers.git_repo')
local M = {}

M.clear_comments_should_preserve_borrowed_source_and_diff_highlights_when_projection_is_replaced = function()
  git_repo.with_repo(function(repo)
    repo:write_file('file', { 'borrowed', 'second' })
    repo:add('file')
    repo:commit('source')
    h.with_ui(function(review_ui)
      local diff = { file_id = 'file', operation = 'added', current = h.models.path(repo.cwd .. '/file') }
      review_ui:display_diff_side_by_side(diff, 'vertical')
      local buffer = h.pane(review_ui, 'borrowed')
      local original_marks = vim.api.nvim_buf_get_extmarks(buffer, -1, 0, -1, { details = true })
      assert(#original_marks == 2)
      assert(review_ui:show_comments('file', { h.comment('path bounds', 'current', 2, 2) }))
      assert(h.blocks(buffer)[1].row == 1)
      review_ui:clear_comments()
      review_ui:clear_comments()
      assert(vim.deep_equal(vim.api.nvim_buf_get_extmarks(buffer, -1, 0, -1, { details = true }), original_marks))
      assert(review_ui:show_comments('file', { h.comment('again', nil) }))
      local unrelated = h.comment('other', nil)
      unrelated.target.file_id = 'other'
      assert(review_ui:show_comments('file', { unrelated }))
      assert(#h.blocks(buffer) == 0)
      assert(review_ui:show_comments('file', { h.comment('again', nil) }))
      review_ui:refresh_selected_diff(diff, 'vertical')
      assert(#h.blocks(buffer) == 0)
      assert(review_ui:show_comments('file', { h.comment('again', nil) }))
      local other_diff = vim.deepcopy(diff)
      other_diff.file_id = 'other'
      review_ui:display_diff_side_by_side(other_diff, 'horizontal')
      assert(#h.blocks(buffer) == 0 and not review_ui:show_comments('file', {}))
      assert(review_ui:show_comments('other', {}))
      review_ui:clear_selected_diff()
      assert(not review_ui:show_comments('other', {}))
      assert(vim.api.nvim_buf_is_valid(buffer) and not vim.bo[buffer].modified)
      assert(vim.deep_equal(vim.api.nvim_buf_get_lines(buffer, 0, -1, false), { 'borrowed', 'second' }))
      review_ui:display_diff_side_by_side(diff, 'vertical')
      assert(review_ui:show_comments('file', { h.comment('cleanup', nil) }))
      review_ui:cleanup()
      assert(vim.api.nvim_buf_is_valid(buffer) and #h.blocks(buffer) == 0 and not vim.bo[buffer].modified)
    end)
  end)
end

M.clear_comments_should_tolerate_deleted_buffers_when_panes_are_lost = function()
  h.with_ui(function(review_ui)
    review_ui:display_diff_side_by_side(h.models.modified({ 'old' }, { 'current' }), 'vertical')
    local old, win = h.pane(review_ui, 'old')
    assert(review_ui:show_comments('file', { h.comment('body', 'old', 1, 1) }))
    vim.api.nvim_win_close(win, false)
    assert(not review_ui:show_comments('file', {}))
    vim.api.nvim_buf_delete(old, { force = true })
    review_ui:clear_comments()
    review_ui:cleanup()
  end)
end

return M
